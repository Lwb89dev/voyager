#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PIN="$ROOT/roadstr-integration/upstream.properties"
MIRROR="${ROADSTR_NATIVE_MIRROR:-$ROOT/.roadstr-native}"
PREPARE_ONLY=0
if [[ "${1:-}" == "--prepare-only" ]]; then
  PREPARE_ONLY=1
elif [[ $# -gt 0 ]]; then
  echo "Usage: tools/update_roadstr.sh [--prepare-only]" >&2
  exit 2
fi

property() {
  local key="$1" line
  while IFS='=' read -r name value; do
    if [[ "$name" == "$key" ]]; then
      printf '%s\n' "$value"
      return
    fi
  done < "$PIN"
  echo "Missing $key in $PIN" >&2
  exit 1
}

REPOSITORY="$(property repository)"
REVISION="$(property revision)"
VERSION="$(property version)"
[[ "$REVISION" =~ ^[0-9a-f]{40}$ ]] || { echo "The Roadstr pin must be a full commit SHA" >&2; exit 1; }

if [[ -e "$MIRROR" && ! -f "$MIRROR/.voyager-managed" ]]; then
  echo "Refusing to reset unmarked directory: $MIRROR" >&2
  echo "Move it away or use ROADSTR_NATIVE_MIRROR for a generated checkout." >&2
  exit 1
fi

if [[ ! -d "$MIRROR/.git" ]]; then
  rm -rf "$MIRROR"
  git clone --no-checkout "$REPOSITORY" "$MIRROR"
fi

# This directory is an explicitly managed build input, never a user working tree.
git -C "$MIRROR" reset --hard
git -C "$MIRROR" clean -fd
printf 'Generated by tools/update_roadstr.sh; local changes are discarded.\n' > "$MIRROR/.voyager-managed"
git -C "$MIRROR" fetch --depth 1 origin "$REVISION"
git -C "$MIRROR" checkout --detach "$REVISION"
ACTUAL="$(git -C "$MIRROR" rev-parse HEAD)"
[[ "$ACTUAL" == "$REVISION" ]] || { echo "Roadstr revision mismatch: $ACTUAL" >&2; exit 1; }

shopt -s nullglob
patches=("$ROOT"/patches/roadstr-native/*.patch)
for patch_file in "${patches[@]}"; do
  git -C "$MIRROR" apply --check "$patch_file"
  git -C "$MIRROR" apply "$patch_file"
  echo "Applied $(basename "$patch_file")"
done
git -C "$MIRROR" diff --check

echo "Roadstr $VERSION prepared at $ACTUAL"
if (( PREPARE_ONLY )); then
  exit 0
fi

cd "$ROOT/android"
./gradlew :roadstr-integration:compileDebugKotlin :app:testDebugUnitTest :app:assembleDebug
